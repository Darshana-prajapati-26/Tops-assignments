# Write a Python program to read a string, an integer,
#  and a float from the keyboard and display them.

# Reading a string from the keyboard
string_input = input("Enter a string: ")

# Reading an integer from the keyboard
integer_input = int(input("Enter an integer: "))

# Reading a float from the keyboard
float_input = float(input("Enter a float: "))

# Displaying the inputs
print(f"You entered the string: {string_input}")
print(f"You entered the integer: {integer_input}")
print(f"You entered the float: {float_input}")

